import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const source = readFileSync('public/imports.js','utf8');
const logic = source.slice(source.indexOf('const schemas='), source.indexOf("document.addEventListener('click',e=>{const b=e.target.closest('[data-template]')"));
const context = { state: { classes: [{name:'9/1',grade:'9'}], teachers:[{name:'Cô Lan'}], subjects:[{grade:'9',name:'Toán',periods:3}], assignments:[], events:[], closed:[] }, ScheduleLogic:require('../public/schedule-logic.js'), gradeOf: c => c.grade || '' };
runInNewContext(logic + String.raw`
 const parsed=parseCsv('Lớp,Môn học,Giáo viên,Số tiết\r\n9/1,"Toán",Cô Lan,2');
 const good=validateRows('assignments',parsed);
 if(good.errors.length || good.data[0].periods!==2) throw Error('valid assignment rejected');
 const other=validateRows('assignments',parseCsv('Giáo viên,Lớp,Môn,Tiết/Tuần\r\nCô Lan,9/1,GDĐP,1'));
 if(other.errors.length||other.data[0].subject!=='GDĐP')throw Error('subjects must not require grade-level declarations');
 const invalid=validateRows('classes',parseCsv('Tên lớp,Khối,Buổi\r\n9/1,9,Sáng'));
 if(invalid.errors.length!==1) throw Error('duplicate class accepted');
 const events=validateRows('events',parseCsv('Hoạt động,Buổi,Thứ,Tiết\r\nChào cờ,Sáng,2,1'));
 if(events.errors.length || events.data[0].day!==0) throw Error('invalid event mapping');
 const weekend=validateRows('events',parseCsv('Hoạt động,Buổi,Thứ,Tiết\r\nSinh hoạt,Sáng,7,5'));
 if(weekend.errors.length!==1) throw Error('Saturday must not be accepted');
 const teachers=validateRows('teachers',parseCsv('Giáo viên\r\nThầy Minh'));
 if(teachers.errors.length || teachers.data[0].name!=='Thầy Minh' || 'maxSessions' in teachers.data[0]) throw Error('teacher name-only import');
 const oldTeachers=validateRows('teachers',parseCsv('Giáo viên,Số buổi tối đa\r\nThầy Minh,7'));
 if(oldTeachers.errors.length || 'maxSessions' in oldTeachers.data[0]) throw Error('legacy teacher columns should be ignored');
 const reuse=validateRows('assignments',parseCsv('Giáo viên,Lớp,Môn,Tiết/Tuần\r\n  cô   lan  ,9/1,GDĐP,1'));
 if(reuse.errors.length||reuse.newTeachers.length||reuse.data[0].teacher!=='Cô Lan')throw Error('existing teacher must be reused');
 const duplicates=validateRows('teachers',parseCsv('Giáo viên\r\nCÔ LAN\r\nThầy Minh\r\n thầy   minh '));
 if(duplicates.errors.length||duplicates.data.length!==1||duplicates.skippedTeachers.length!==2)throw Error('duplicate teacher rows must be skipped');
 const split=parseCsv('a,b\r\n"hello, world","a""b"');
 if(split[1][0]!=='hello, world'||split[1][1]!=='a"b')throw Error('CSV quoting');
 state.classes=[{name:'9/1',grade:'9'},{name:'9/2',grade:'9'},{name:'7/5',grade:'7'}];state.subjects=[];state.teachers=[];
 const table=parseCsv('Giáo Viên,Lớp,Môn,Tiết/Tuần\r\nT.Sương,9/1,Văn,4\r\n,9/2,Văn,4\r\n,7/5,Văn,4\r\n,9/1,GDĐP,1\r\n,9/2,GDĐP,1');
 const grouped=validateRows('assignments',table);
 if(grouped.errors.length||grouped.data.length!==5||grouped.data.some(x=>x.teacher!=='T.Sương')||grouped.newTeachers.length!==1||grouped.rows[2][0]!=='T.Sương')throw Error('grouped teacher rows should fill down and preview');
 const missing=validateRows('assignments',parseCsv('Giáo viên,Lớp,Môn,Tiết/Tuần\r\n,9/1,Văn,4'));
 if(missing.errors.length!==1)throw Error('first teacher is required');
 const gap=validateRows('assignments',parseCsv('Giáo viên,Lớp,Môn,Tiết/Tuần\r\nT.Sương,9/1,Văn,4\r\n\r\n,9/2,Văn,4'));
 if(gap.errors.length!==1||!gap.errors[0].includes('Dòng 4'))throw Error('blank row must end group');
 state.classes=[{name:'9/1',grade:'9'}];state.teachers=[{name:'Cô Lan'}];state.subjects=[{grade:'9',name:'Toán',periods:3}];
`, context);
assert.ok(true);
console.log('Import validation and CSV parsing passed');
